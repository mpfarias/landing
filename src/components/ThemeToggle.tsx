export function ThemeToggle() {
  const { messages } = useLanguage();
  const { resolvedTheme, setTheme } = useTheme();
  const [mounted, setMounted] = useState(false);

  useEffect(() => {
    setMounted(true);
  }, []);

  if (!mounted) {
    return (
      <span
        className="inline-flex h-10 w-10 items-center justify-center rounded-full border border-slate-200 bg-white/80 dark:border-white/10 dark:bg-slate-950/80"
        aria-hidden
      />
    );
  }

  const isDark = resolvedTheme === "dark";

  return (
    <button
      type="button"
      onClick={() => setTheme(isDark ? "light" : "dark")}
      className="inline-flex h-10 w-10 items-center justify-center rounded-full border border-slate-200 bg-white text-amber-500 transition hover:border-cyan-400/50 hover:text-cyan-600 dark:border-white/10 dark:bg-slate-950/80 dark:text-amber-300 dark:hover:border-cyan-300/50 dark:hover:text-cyan-300"
      aria-label={isDark ? messages.theme.toLight : messages.theme.toDark}
    >
      {isDark ? (
        <SunIcon className="h-5 w-5" />
      ) : (
        <MoonIcon className="h-5 w-5" />
      )}
    </button>
  );
}
